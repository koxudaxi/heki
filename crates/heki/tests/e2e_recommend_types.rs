//! `heki recommend`'s suggestions end to end (ADR-023): the kind `readonly-parameter`, a true
//! and a false case of each of its premises, the groups, the annotation trial withholding a
//! group, the labels, the edits, the type checker heki finds, the JSON object against the
//! published schema, and that two runs print the same report. One judgment has two readers:
//! with every exact suggestion applied, `MUT110` reports nothing new.

