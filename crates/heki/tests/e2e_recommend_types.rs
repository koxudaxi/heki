/// A project with a suggestion, and a case left out, for each premise of the kind.
fn project(name: &str) -> Project {
    let p = Project::new(name);
    p.write("pyproject.toml", "[project]\nname = \"t\"\n\n[tool.mypy]\nstrict = true\n")
        .write("app/__init__.py", "")
        .write("app/core.py", CORE)
        .write("app/names.py", NAMES)
        .write(
            "app/patch.py",
            "from app import core\n\n\ndef install() -> None:\n    core.patched = lambda rows: True\n",
        )
        .write(
            "app/wrap.py",
            "from app import core\nfrom app.deco import traced\n\nwrapped = traced(core.wrapped)\n",
        )
        .write("app/deco.py", "def traced(f):\n    return f\n")
        .write(
            "app/taken.py",
            "from sqlalchemy import Sequence\n\n\ndef clash(rows: list[int]) -> bool:\n    return 1 in rows\n",
        )
        .write(
            "app/gen.py",
            "# Code generated by a tool. DO NOT EDIT.\ndef gen(rows: list[int]) -> bool:\n    return 1 in rows\n",
        )
        .write(
            "app/stubbed.py",
            "def stubbed(rows: list[int]) -> bool:\n    return 1 in rows\n",
        )
        .write("app/stubbed.pyi", "def stubbed(rows: list[int]) -> bool: ...\n")
        .write(
            "tests/test_core.py",
            "def helper(rows: list[int]) -> bool:\n    return 1 in rows\n",
        );
    p
}

fn recommend(p: &Project, args: &[&str]) -> (Value, String) {
    let mut all = vec!["recommend", "--output-format", "json"];
    all.extend_from_slice(args);
    let (code, out, err) = p.heki(&all);
    assert_eq!(code, 0, "{err}");
    (
        serde_json::from_str(&out).unwrap_or_else(|e| panic!("{e}: {out}{err}")),
        out,
    )
}

/// The groups by id, without the kind.
fn groups(report: &Value) -> BTreeMap<String, &Value> {
    report["suggestions"]["groups"]
        .as_array()
        .unwrap()
        .iter()
        .map(|g| {
            let id = g["id"].as_str().unwrap();
            (id.trim_start_matches("readonly-parameter:").to_owned(), g)
        })
        .collect()
}

fn open_premises(group: &Value) -> Vec<&str> {
    let mut names: Vec<&str> = (group["open"].as_array().unwrap().iter())
        .map(|o| o["premise"].as_str().unwrap())
        .collect();
    names.dedup();
    names
}

fn by_premise(report: &Value, premise: &str) -> (u64, u64) {
    report["suggestions"]["by_premise"]
        .as_array()
        .unwrap()
        .iter()
        .find(|r| r["premise"] == premise)
        .map_or((0, 0), |r| {
            (
                r["not_listed"].as_u64().unwrap(),
                r["heuristic"].as_u64().unwrap(),
            )
        })
}

fn withheld(report: &Value) -> BTreeMap<String, String> {
    (report["suggestions"]["withheld"].as_array().unwrap().iter())
        .flat_map(|w| w["first"].as_array().unwrap())
        .map(|g| {
            let id = g["id"].as_str().unwrap();
            let id = id.trim_start_matches("readonly-parameter:").to_owned();
            (id, g["changed"].as_str().unwrap().to_owned())
        })
        .collect()
}

#[test]
fn each_premise_keeps_a_parameter_or_leaves_it_out() {
    let p = project("recommend_types_premises");
    let (report, _) = recommend(&p, &["--all"]);
    let found = groups(&report);
    let groups = &found;
    let exact = |id: &str| {
        let g = groups
            .get(id)
            .unwrap_or_else(|| panic!("{id}: {groups:#?}"));
        assert_eq!(g["certainty"], "exact", "{id}: {g:#}");
        assert!(g["open"].as_array().unwrap().is_empty(), "{id}: {g:#}");
        *g
    };
    let heuristic = |id: &str, premise: &str| {
        let g = groups
            .get(id)
            .unwrap_or_else(|| panic!("{id}: {groups:#?}"));
        assert_eq!(g["certainty"], "heuristic", "{id}: {g:#}");
        assert_eq!(open_premises(g), [premise], "{id}: {g:#}");
    };
    let absent = |id: &str| assert!(!groups.contains_key(id), "{id}: {:#}", groups[id]);
    // The claim: only read here, does not leave, every call only reads.
    let total = exact("app.core:total:rows");
    assert_eq!(total["items"][0]["current"], "list[int]");
    assert_eq!(total["items"][0]["proposed"], "Sequence[int]");
    absent("app.core:grow:items");
    absent("app.core:keep:items");
    absent("app.core:hand:items");
    assert_eq!(by_premise(&report, "Only read here").0, 1);
    assert_eq!(by_premise(&report, "Does not leave").0, 2);
    // Literal container annotation: a `Mutable*` ABC or `Annotated[...]` is no candidate.
    absent("app.core:stated:items");
    absent("app.core:noted:items");
    exact("app.core:members:tags");
    // Abstract use: a `.copy()` the read-only type lacks keeps it heuristic before the trial.
    assert!(!groups.contains_key("app.core:copied:rows"));
    assert_eq!(by_premise(&report, "Abstract use").1, 1);
    // Name bound once.
    heuristic("app.core:rebound:rows", "Name bound once");
    // Callees take it: a callee's literal container joins the group; a `MutableSequence`
    // parameter does not take a `Sequence`.
    let outer = exact("app.core:outer:rows");
    let targets: Vec<&str> = (outer["items"].as_array().unwrap().iter())
        .map(|i| i["qualname"].as_str().unwrap())
        .collect();
    assert_eq!(targets, ["outer", "_inner"]);
    absent("app.core:_inner:rows");
    heuristic("app.core:outer_mutable:rows", "Callees take it");
    // Whole family: an override family is one group; a Protocol member, a stub body alone, and
    // overloads are not listed.
    let family = exact("app.core:Base.has:rows");
    assert_eq!(family["items"].as_array().unwrap().len(), 2);
    assert!(
        family["labels"]
            .as_array()
            .unwrap()
            .contains(&"family".into())
    );
    absent("app.core:Shape.has:rows");
    absent("app.core:Iface.has:rows");
    absent("app.core:pick:rows");
    assert_eq!(by_premise(&report, "Whole family").0, 3);
    // Not replaced: another module stores into it.
    heuristic("app.core:patched:rows", "Not replaced");
    // Annotations stay unread: a catalog reader leaves it out, a value use and an unknown
    // decorator keep it heuristic.
    absent("app.core:validated:rows");
    assert_eq!(by_premise(&report, "Annotations stay unread").0, 1);
    heuristic("app.core:handler:rows", "Annotations stay unread");
    heuristic("app.core:wrapped:rows", "Annotations stay unread");
    // A file to edit: a generated file and a stubbed function are left out, as test code is.
    absent("app.gen:gen:rows");
    absent("app.stubbed:stubbed:rows");
    absent("tests.test_core:helper:rows");
    let left_out = &report["suggestions"]["left_out"];
    assert_eq!(left_out["generated_files"], 1);
    assert_eq!(left_out["stubs"], 1);
    assert_eq!(left_out["test_code"], 1);
    // A name for the type: a binding is reused, a `typing` module's prefix kept, and a name
    // bound to another object keeps it heuristic.
    let bound = exact("app.names:bound:rows");
    let replacements: Vec<&str> = (bound["edits"].as_array().unwrap().iter())
        .map(|e| e["replacement"].as_str().unwrap())
        .collect();
    assert_eq!(replacements, ["Sequence"]);
    assert_eq!(
        exact("app.names:dotted:rows")["items"][0]["proposed"],
        "t.Sequence[int]"
    );
    heuristic("app.taken:clash:rows", "A name for the type");
    // The `list[str]` label holds a suggestion back with no premise open.
    let named = &groups["app.core:named:rows"];
    assert_eq!(named["certainty"], "heuristic");
    assert!(
        named["labels"]
            .as_array()
            .unwrap()
            .contains(&"list[str]".into())
    );
    // Without `--all`, only the exact groups are listed.
    let (default, _) = recommend(&p, &[]);
    let shown = self::groups(&default);
    assert!(
        shown.values().all(|g| g["certainty"] == "exact"),
        "{shown:#?}"
    );
    assert_eq!(
        default["suggestions"]["counts"],
        report["suggestions"]["counts"]
    );
}

#[test]
fn the_trial_withholds_a_group_whose_edit_changes_what_heki_knows() {
    let p = project("recommend_types_trial");
    let (report, _) = recommend(&p, &["--all"]);
    let withheld = withheld(&report);
    // A `Mapping`'s `get` is not one heki knows to only read, as a `dict`'s is.
    let changed = &withheld["app.core:lookup:table"];
    assert!(changed.contains("only_read_params"), "{changed}");
    assert!(!groups(&report).contains_key("app.core:lookup:table"));
    let runs: Vec<&Value> = report["runs"]
        .as_array()
        .unwrap()
        .iter()
        .map(|r| &r["label"])
        .collect();
    assert_eq!(runs[..2], ["discovery", "annotation-trial"]);
}

#[test]
fn a_group_says_what_it_needs_and_what_guards_it() {
    let p = project("recommend_types_group");
    let (report, _) = recommend(&p, &[]);
    let section = &report["suggestions"];
    assert_eq!(section["type_checker"]["found"], "mypy");
    assert_eq!(section["type_checker"]["config"], "pyproject.toml");
    let groups = groups(&report);
    let outer = groups["app.core:outer:rows"];
    // One import, then the two heads, all in one group.
    let edits: Vec<&str> = (outer["edits"].as_array().unwrap().iter())
        .map(|e| e["replacement"].as_str().unwrap())
        .collect();
    assert_eq!(
        edits,
        [
            "from collections.abc import Sequence\n",
            "Sequence",
            "Sequence"
        ]
    );
    let core = p.read("app/core.py");
    let head = &outer["items"][1]["span"];
    let at = |i: usize| usize::try_from(head[i].as_u64().unwrap()).unwrap();
    assert_eq!(&core[at(0)..at(1)], "list");
    assert!(
        outer["labels"]
            .as_array()
            .unwrap()
            .contains(&"public".into())
    );
    assert_eq!(
        outer["related"][0]["message"],
        "`outer` hands `rows` to `app.core._inner`"
    );
    let guards: Vec<&str> = (outer["guards"].as_array().unwrap().iter())
        .map(|g| g["by"].as_str().unwrap())
        .collect();
    assert_eq!(guards, ["type-checker", "heki"]);
    assert_eq!(outer["guards"][1]["rule"], "MUT110");
    let set = groups["app.core:members:tags"];
    assert_eq!(set["items"][0]["proposed"], "AbstractSet[str]");
    assert_eq!(
        set["edits"][0]["replacement"],
        "from collections.abc import Set as AbstractSet\n"
    );
    let established =
        (outer["premises"].as_array().unwrap().iter()).all(|p| p["established"] == true);
    assert!(established, "{outer:#}");
}

#[test]
fn two_runs_print_the_same_object_and_it_follows_the_schema() {
    let p = project("recommend_types_schema");
    let (first, text) = recommend(&p, &["--all"]);
    let (_, again) = recommend(&p, &["--all"]);
    assert_eq!(text, again);
    let (code, out, _) = p.heki(&["recommend", "--output-format-json-schema"]);
    assert_eq!(code, 0);
    let published: Value = serde_json::from_str(&out).unwrap();
    let errors = schema::errors(&published, &first);
    assert!(errors.is_empty(), "{errors:#?}");
}

/// The exact groups' edits applied to the project's files, each file's from its end.
fn apply_exact(p: &Project, report: &Value) {
    let mut by_file: BTreeMap<String, Vec<(usize, usize, String)>> = BTreeMap::new();
    for g in report["suggestions"]["groups"].as_array().unwrap() {
        if g["certainty"] != "exact" {
            continue;
        }
        for e in g["edits"].as_array().unwrap() {
            let span = &e["span"];
            let at = |i: usize| usize::try_from(span[i].as_u64().unwrap()).unwrap();
            let edit = (at(0), at(1), e["replacement"].as_str().unwrap().to_owned());
            let edits = by_file
                .entry(e["path"].as_str().unwrap().to_owned())
                .or_default();
            if !edits.contains(&edit) {
                edits.push(edit);
            }
        }
    }
    for (path, mut edits) in by_file {
        let mut text = p.read(&path);
        edits.sort();
        for (start, end, replacement) in edits.into_iter().rev() {
            text.replace_range(start..end, &replacement);
        }
        p.write(&path, &text);
    }
}

#[test]
fn applied_suggestions_give_their_guard_nothing_to_report() {
    let p = project("recommend_types_guard");
    let mut_110 = |p: &Project| {
        let (_, out, err) = p.heki(&[
            "check",
            "--select",
            "MUT110",
            "--heuristic",
            "--output-format",
            "json",
        ]);
        let reports: Vec<Value> =
            serde_json::from_str(&out).unwrap_or_else(|e| panic!("{e}: {err}"));
        reports
    };
    assert!(mut_110(&p).is_empty());
    let (report, _) = recommend(&p, &[]);
    assert!(!groups(&report).is_empty());
    apply_exact(&p, &report);
    assert!(
        p.read("app/core.py")
            .contains("def total(rows: Sequence[int])")
    );
    assert!(mut_110(&p).is_empty());
}
