"""Tests of `build_docs.py`'s checks of the rule certainties and of the tables it writes into
`docs/precision.md`: every exact rule has a certification free of false claims, and every rule
says what a report states.

The other checks run end to end in `crates/heki/tests/e2e_experimental.rs`; these are tested on
rules given here.
"""

from __future__ import annotations

from pathlib import Path

import build_docs
import pytest


def certification(census_false: int, holdout_false: int) -> dict:
    return {
        "rule": "OPT110",
        "release": "0.3.0",
        "census": {"reports": 240, "false_claims": census_false},
        "holdout": {"reports": 31, "false_claims": holdout_false},
    }


@pytest.mark.parametrize(
    ("census_false", "holdout_false", "stale"),
    [
        (0, 0, []),
        (1, 0, ["OPT110: 1 false claim(s) in the census and 0 in the holdout run (exact needs none)"]),
        (0, 2, ["OPT110: 0 false claim(s) in the census and 2 in the holdout run (exact needs none)"]),
    ],
)
def test_an_exact_rule_needs_no_false_claim_in_its_census_and_holdout_run(
    census_false: int, holdout_false: int, stale: list[str]
) -> None:
    rules = [
        {
            "code": "OPT110",
            "certainty": "exact",
            "certification": certification(census_false, holdout_false),
        }
    ]
    assert build_docs.uncertified_exact_rules(rules) == stale


def test_an_exact_rule_without_a_certification_fails_and_a_heuristic_one_needs_none() -> None:
    rules = [
        {"code": "OPT110", "certainty": "exact", "certification": None},
        {"code": "EFF102", "certainty": "heuristic", "certification": None},
    ]
    assert build_docs.uncertified_exact_rules(rules) == ["OPT110: no certification"]


MEASUREMENT = {
    "rule": "EFF102",
    "round": 3,
    "date": "2026-11-21",
    "sample": 50,
    "confirmed": 0,
    "plausible": 2,
    "benign": 25,
    "false_claims": 23,
    "right_percent": 54,
    "interval_percent": [40, 67],
    "real_harm_percent": 4,
}


def test_the_tables_are_written_from_the_data() -> None:
    precision = {"certifications": [certification(0, 0)], "measurements": [MEASUREMENT]}
    assert build_docs.certifications_table(precision).splitlines()[2] == (
        "| `OPT110` | 0.3.0 | 240 / 0 | 31 / 0 |"
    )
    rules = [{"code": "EFF102", "certainty": "heuristic"}]
    assert build_docs.measurements_table(precision, rules).splitlines()[2] == (
        "| `EFF102` | heuristic | round 3, 2026-11-21 | 50 | 0 / 2 / 25 / 23 | 54% | 40-67% | 4% |"
    )
    assert build_docs.measured(MEASUREMENT) == (
        "Of 50 sampled reports (round 3, 2026-11-21), 54% were right about the code."
    )


def test_only_the_generated_parts_of_a_page_are_replaced(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(build_docs, "ROOT", tmp_path)
    page = tmp_path / "page.md"
    mark = "<!-- Generated by scripts/build_docs.py from data.rs: {name}. -->"
    end = "<!-- End of the generated {name}. -->"
    page.write_text(
        f"Intro.\n\n{mark.format(name='one')}\n\nold\n\n{end.format(name='one')}\n\n"
        f"{mark.format(name='two')}\n\nkept\n\n{end.format(name='two')}\n",
        encoding="utf-8",
    )
    text = build_docs.with_generated_parts(page, {"one": "| new |\n"})
    assert text == page.read_text(encoding="utf-8").replace("\nold\n", "\n| new |\n")
    with pytest.raises(SystemExit, match="^page.md: no generated part named three$"):
        build_docs.with_generated_parts(page, {"three": "x\n"})


def test_every_rule_says_what_a_report_states() -> None:
    rules = [
        {"code": "EFF101", "doc": "## What it does\nx\n\n## What a report states\ny\n"},
        {"code": "EFF102", "doc": "## What it does\nx\n"},
    ]
    assert build_docs.rules_without_claims(rules) == [
        "EFF102: no `## What a report states` section"
    ]


def page(premises: list[str]) -> str:
    bullets = "\n".join(f"- **{name}**: what it states." for name in premises)
    return f"## What it does\nx\n\n## What a report states\n\nIts premises:\n\n{bullets}\n\n## Why\ny\n"


@pytest.mark.parametrize(
    ("listed", "stale"),
    [
        (["Every return", "Waits"], []),
        (
            ["Waits", "Every return"],
            ["EFF101: the page lists ['Waits', 'Every return'], the premise table ['Every return', 'Waits']"],
        ),
        (
            ["Every return"],
            ["EFF101: the page lists ['Every return'], the premise table ['Every return', 'Waits']"],
        ),
    ],
)
def test_a_rule_page_lists_the_premises_of_the_table(listed: list[str], stale: list[str]) -> None:
    rule = {
        "code": "EFF101",
        "certainty": "exact",
        "doc": page(listed),
        "premises": [{"name": "Every return"}, {"name": "Waits"}],
    }
    assert build_docs.premises_disagreeing([rule]) == stale


def test_a_heuristic_rule_without_premises_needs_none() -> None:
    rule = {"code": "EFF111", "certainty": "heuristic", "doc": page(["On every path"]), "premises": []}
    assert build_docs.premises_disagreeing([rule]) == []
