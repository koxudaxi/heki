"""Generate the rules reference and the CLI reference from the `heki` binary.

- `docs/rules/index.md`: every rule, grouped by family, in Ruff's rules-page layout.
- `docs/rules/<slug>.md`: one page per rule (metadata + the rule documentation that
  `heki rule <CODE>` prints, kept in `crates/heki_rules/rule-docs/<CODE>.md`).
- `docs/cli-reference.md`: the `--help` output of every command.
- `docs/experimental.md`: the experimental features (`crates/heki_rules/src/experimental.rs`).
- `docs/precision.md`: the tables of the certifications and the measurements
  (`crates/heki_rules/src/precision.rs`), between the markers of its generated parts.
- `docs/recommend.md`: the report of `heki recommend` on the example project the page shows.
- `docs/getting-started.md`: the list of the exact rules, between the markers of its generated
  part.
- `docs/schemas/recommend-2.json`: the JSON Schema of `heki recommend --output-format json`
  (`recommend-1.json` stays published, unchanged, for the objects of version 1).
- `docs/assets/example-check.svg`: `heki check --color always` on the README's examples, drawn
  as a terminal shows it (`scripts/ansi_svg.py`).

The hand-written pages are checked against the rules: the guides' lists of opt-in rules, the
experimental features and the heuristic rules (in the README, `ARCHITECTURE.md`, and the site's
pages, a table row that names a rule in a cell of its own says "experimental" exactly when the
rule is, and "heuristic" exactly when it is; the `CHANGELOG.md` section of the release an entry
names as `since` calls its target experimental), the certifications (every exact rule has one
whose census and holdout run found no false claim), and the rule documentation (every rule says
what a report states).

Usage:
    python scripts/build_docs.py --heki target/release/heki
    python scripts/build_docs.py --heki target/release/heki --check  # CI: fail when stale
"""

