def shown(path: Path) -> str:
    """A file of the repository as the messages name it: relative, with `/` on every platform."""
    return path.relative_to(ROOT).as_posix()


def run(heki: Path, *args: str) -> str:
    out = subprocess.run([str(heki), *args], capture_output=True, text=True, check=False)
    if out.returncode != 0:
        sys.exit(f"`heki {' '.join(args)}` failed ({out.returncode}):\n{out.stderr}")
    return out.stdout


def fix_label(rule: dict) -> str:
    if rule["auto_fix_default"]:
        return "Safe fix (`--fix`)"
    if rule["size_dependent_fix"]:
        return "Proven-safe suggestion (`--fix --include-size-dependent`)"
    if rule["unsafe_fix"]:
        return "Unsafe fix (`--fix --unsafe-fixes`)"
    return "No automatic fix"


def badges(rule: dict) -> str:
    marks = []
    if rule["auto_fix_default"]:
        marks.append("🛠️")
    elif rule["size_dependent_fix"]:
        marks.append("🔧")
    if rule["certainty"] == "heuristic":
        marks.append("≈")
    if rule["activation"] == "opt-in":
        marks.append("🔌")
    elif rule["activation"] == "contract":
        marks.append("📜")
    if rule["experimental"]:
        marks.append("🧪")
    return " ".join(marks)


def activation_label(rule: dict) -> str:
    if rule["activation"] == "opt-in":
        return "Opt-in"
    if rule["activation"] == "contract":
        return "Runs when its contract is declared"
    if rule["default_enabled"]:
        return "Enabled by default"
    return "Off by default"


def rules_index(rules: list[dict], policy: str) -> str:
    lines = [
        GENERATED,
        "# Rules",
        "",
        f"heki has {len(rules)} rules in four families. A rule is exact when it reports only "
        "what it established and was certified on the corpus, and heuristic (≈) when a report "
        "can be wrong about the code: [Rule Precision](../precision.md) says how a rule is "
        "certified and what each one measured. Each rule's page says what a report states.",
        "",
        "- The exact rules run by default, and for a prefix such as `EFF` or `ALL`. A report "
        "of an exact rule that did not establish every premise (an `OPT` report whose rewrite "
        "is not proven) is shown where a heuristic rule would run.",
        "- A heuristic rule runs when `select` / `extend-select` names its code or name. With "
        "`lint.heuristic = true` (`--heuristic`), the heuristic rules that are not opt-in also "
        "run by default and for a prefix or `ALL`.",
        "- The opt-in rules marked 🔌 run only when `select` / `extend-select` names their exact "
        "code or name.",
        "- The contract rules marked 📜 run when their contract is declared, whatever their "
        "certainty.",
        "",
        "## Legend",
        "",
        "- 🛠️ The fix is applied by `heki check --fix` when heki proves it safe.",
        "- 🔧 A proven-safe rewrite applied only with `--fix --include-size-dependent` (it can be "
        "slower for tiny inputs).",
        "- ≈ Heuristic rule: a report can be wrong about the code. Every output labels its "
        "reports `heuristic`.",
        "- 🔌 Opt-in rule.",
        "- 📜 Contract rule: it reports only what a declared contract asks for.",
        f"- 🧪 Experimental rule. {policy} See [Experimental Features](../experimental.md).",
        "",
    ]
    for family, (title, blurb) in FAMILIES.items():
        members = [r for r in rules if r["family"] == family]
        if not members:
            continue
        lines += [f"## {title}", "", blurb, "", "| Code | Name | Message | |", "| ---- | ---- | ------- | ------: |"]
        for r in members:
            summary = r["summary"].replace("|", "\\|")
            lines.append(f"| {r['code']} | [{r['slug']}]({r['slug']}.md) | {summary} | {badges(r)} |")
        lines.append("")
    return "\n".join(lines)


def when_measured(measurement: dict) -> str:
    return f"round {measurement['round']}, {measurement['date']}"


def measured(measurement: dict | None) -> str:
    """What the latest measurement of a rule found, as its page says it."""
    if measurement is None:
        return "It has not been measured yet."
    return (
        f"Of {measurement['sample']} sampled reports ({when_measured(measurement)}), "
        f"{measurement['right_percent']}% were right about the code."
    )


def rule_page(rule: dict, policy: str) -> str:
    title, _ = FAMILIES[rule["family"]]
    state = [rule["certainty"].capitalize(), activation_label(rule)]
    note = []
    if rule["heuristic_note"]:
        note += [
            '!!! note "Heuristic"',
            "",
            f"    {rule['heuristic_note']} {measured(rule['measurement'])} See "
            "[Rule Precision](../precision.md).",
            "",
        ]
    if rule["experimental"]:
        state.append("Experimental")
        note += [
            '!!! warning "Experimental"',
            "",
            f"    {rule['experimental']['reason']} {policy} See "
            "[Experimental Features](../experimental.md).",
            "",
        ]
    return "\n".join(
        [
            GENERATED,
            f"# {rule['slug']} ({rule['code']})",
            "",
            f"Family: {title} · {' · '.join(state)} · Severity `{rule['default_severity']}` "
            f"({CONSEQUENCES[rule['consequence']]}) · {fix_label(rule)}",
            "",
            rule["summary"],
            "",
            *note,
            rule["doc"].rstrip(),
            "",
        ]
    )


def experimental_target(feature: dict, slugs: dict[str, str]) -> str:
    """The target as a code span, linked to the rule's page for a rule."""
    if feature["kind"] == "rule":
        return f"[`{feature['target']}`](rules/{slugs[feature['target']]}.md)"
    return f"`{feature['target']}`"


def experimental_page(registry: dict, rules: list[dict]) -> str:
    slugs = {r["code"]: r["slug"] for r in rules}
    features = sorted(registry["features"], key=lambda f: f["id"])
    lines = [
        GENERATED,
        "# Experimental Features",
        "",
        f"{registry['policy']} A feature leaves this page when it becomes stable.",
        "",
        "An experimental rule is never enabled by default: it runs only when `select` or "
        "`extend-select` names its code or name, and `heki check` then reports it like any "
        "other rule. `heki rule <CODE>` and the rule's page say that it is experimental.",
        "",
        "| ID | Kind | Target | Since | Tracking |",
        "| -- | ---- | ------ | ----- | -------- |",
    ]
    for f in features:
        tracking = f"<{f['tracking']}>" if f["tracking"] else "-"
        lines.append(
            f"| `{f['id']}` | {f['kind']} | {experimental_target(f, slugs)} | {f['since']} "
            f"| {tracking} |"
        )
    for f in features:
        lines += [
            "",
            f"## `{f['id']}`",
            "",
            f"- **Kind:** {f['kind']}",
            f"- **Target:** {experimental_target(f, slugs)}",
            f"- **Since:** {f['since']}",
        ]
        if f["tracking"]:
            lines.append(f"- **Tracking:** <{f['tracking']}>")
        lines += ["", f["reason"]]
    return "\n".join(lines) + "\n"


def cli_page(heki: Path) -> str:
    lines = [
        GENERATED,
        "# CLI Reference",
        "",
        "Exit codes: `0` no diagnostic that fails the run (warnings and heuristic reports are "
        "reported without failing it), `1` an exact `error` diagnostic, or any diagnostic with "
        "`--fail-on warning` (`lint.fail-on`), among the Ratchet regressions when a baseline is "
        "used (or a refused `--update-baseline`, or pending `--diff` changes), `2` configuration "
        "/ I/O / syntax errors.",
        "",
        "A file that cannot be read or does not parse does not stop the run: `heki check` reports "
        "its error, checks and reports the other files, and exits with `2`, also when it reports "
        "diagnostics. A run over given files (file PATHS, or `--touched`) reports and fails on "
        "only the errors of those files, as it does with diagnostics, and names the other files "
        "it could not analyze in a note. A file that does not parse cannot run either, so nothing "
        "it would do is "
        "assumed; the names under its module resolve to nothing. SARIF output lists such files as "
        "`error` notifications of a run that did not execute successfully "
        "(`invocations[0].toolExecutionNotifications`, `executionSuccessful: false`); JSON output "
        "holds the diagnostics only.",
        "",
    ]
    for args, title in CLI_COMMANDS:
        help_text = run(heki, *args, "--help").rstrip()
        lines += [f"## `{title}`", "", "```text", help_text, "```", ""]
    return "\n".join(lines)


def example_files(text: str, page: Path) -> dict[str, str]:
    """The files of the Python blocks of `text`, a part of `page`, each named on its first line
    (`# app/users.py`)."""
    files: dict[str, str] = {}
    for language, block in FENCED_BLOCK.findall(text):
        if language == "python":
            path = block.splitlines()[0].removeprefix("# ")
            if path in files:
                sys.exit(f"{shown(page)}: two examples write `{path}`")
            files[path] = block
    return files


def run_in_project(heki: Path, files: dict[str, str], args: list[str]) -> subprocess.CompletedProcess:
    """`heki <args>` in a new project holding `files` (and a `pyproject.toml`), as from a terminal:
    without the variables that choose `heki check`'s output format (`GITHUB_ACTIONS` is set in
    CI)."""
    chosen_format = {"GITHUB_ACTIONS", "HEKI_OUTPUT_FORMAT"}
    terminal = {k: v for k, v in os.environ.items() if k not in chosen_format}
    with tempfile.TemporaryDirectory() as directory:
        project = Path(directory)
        files = {"pyproject.toml": '[project]\nname = "t"\n', **files}
        for path, text in files.items():
            (project / path).parent.mkdir(parents=True, exist_ok=True)
            (project / path).write_text(text, encoding="utf-8", newline="\n")
        return subprocess.run(
            [str(heki), *args],
            capture_output=True,
            cwd=project,
            encoding="utf-8",
            check=False,
            env=terminal,
        )


def recommend_example(heki: Path) -> str:
    """The report `heki recommend` prints on the example project of `docs/recommend.md`."""
    files = example_files(RECOMMEND_PAGE.read_text(encoding="utf-8"), RECOMMEND_PAGE)
    out = run_in_project(heki, files, list(RECOMMEND_EXAMPLE))
    if out.returncode != 0:
        sys.exit(f"`heki recommend` on the example of {shown(RECOMMEND_PAGE)} failed:\n{out.stderr}")
    return f"```console\n$ heki {' '.join(RECOMMEND_EXAMPLE)}\n{out.stdout}```\n"


def readme_examples(readme: str) -> tuple[str, dict[str, str]]:
    """The command the README's examples run, and the files of all of them: each Python block
    names its file on its first line (`# app/users.py`)."""
    start = readme.index("\n### ")
    examples = readme[start : readme.index(EXAMPLES_END, start)]
    files = example_files(examples, README)
    commands = {
        text.splitlines()[0].removeprefix("$ ")
        for language, text in FENCED_BLOCK.findall(examples)
        if language == "console"
    }
    if len(commands) != 1:
        sys.exit(f"README.md: the examples run different commands: {sorted(commands)}")
    return commands.pop(), files


def example_image(heki: Path) -> str:
    """The command of the README's examples, run with `--color always` in one project holding
    the files of all of them, drawn as a terminal shows what it prints."""
    command, files = readme_examples(README.read_text(encoding="utf-8"))
    out = run_in_project(heki, files, [*command.split()[1:], "--color", "always"])
    # The first example's exact error fails the run (exit code 1); exit code 2 says the examples
    # could not be checked.
    if out.returncode not in (0, 1):
        sys.exit(f"`{command}` on the README's examples failed ({out.returncode}):\n{out.stderr}")
    prompt = f"\x1b[36m$\x1b[0m {command}\n"
    return ansi_svg.render(prompt + out.stdout + out.stderr, TERMINAL_COLUMNS, EXAMPLE_IMAGE_TITLE)


def certifications_table(precision: dict, rules: list[dict]) -> str:
    """The certifications; a certified rule that is still experimental (opt-in for its harm
    share) says so in its row."""
    experimental = {r["code"] for r in rules if r["experimental"]}
    lines = [
        "| Rule | Certified | Census: reports / false | Holdout: reports / false |",
        "| ---- | --------- | ----------------------: | -----------------------: |",
    ]
    for c in precision["certifications"]:
        census, holdout = c["census"], c["holdout"]
        release = c["release"] + (" (experimental)" if c["rule"] in experimental else "")
        lines.append(
            f"| `{c['rule']}` | {release} | {census['reports']} / {census['false_claims']} "
            f"| {holdout['reports']} / {holdout['false_claims']} |"
        )
    return "\n".join(lines) + "\n"


def harm_table(precision: dict) -> str:
    """The harm of the exact reports of the certifications whose census and holdout run classed
    it."""
    lines = [
        "| Rule | Census: C / P / B / not classified | Holdout: C / P / B / not classified |",
        "| ---- | ---------------------------------- | ----------------------------------- |",
    ]

    def classes(harm: dict) -> str:
        return " / ".join(
            str(harm[k]) for k in ("confirmed", "plausible", "benign", "unclassified")
        )

    for c in precision["certifications"]:
        census, holdout = c["census"].get("harm"), c["holdout"].get("harm")
        if census is not None and holdout is not None:
            lines.append(f"| `{c['rule']}` | {classes(census)} | {classes(holdout)} |")
    return "\n".join(lines) + "\n"


def measurements_table(precision: dict, rules: list[dict]) -> str:
    """The measurements, each with the rule's certainty now."""
    certainty = {r["code"]: r["certainty"] for r in rules}
    lines = [
        "| Rule | Certainty | Measured | Sample | C / P / B / F | Right about the code "
        "| 95% interval | Real harm |",
        "| ---- | --------- | -------- | -----: | ------------- | -------------------: "
        "| ------------ | --------: |",
    ]
    for m in precision["measurements"]:
        low, high = m["interval_percent"]
        classes = f"{m['confirmed']} / {m['plausible']} / {m['benign']} / {m['false_claims']}"
        lines.append(
            f"| `{m['rule']}` | {certainty[m['rule']]} | {when_measured(m)} | {m['sample']} "
            f"| {classes} | {m['right_percent']}% | {low}-{high}% | {m['real_harm_percent']}% |"
        )
    return "\n".join(lines) + "\n"


def default_rules_list(rules: list[dict]) -> str:
    """The rules a run without configuration runs: the exact rules that are not opt-in."""
    return "".join(
        f"- [`{r['code']}` ({r['slug']})](rules/{r['slug']}.md)\n"
        for r in rules
        if r["certainty"] == "exact" and r["activation"] == "default"
    )


def with_generated_parts(page: Path, parts: dict[str, str]) -> str:
    """The text of the hand-written `page` with the body of each generated part in `parts`
    replaced."""
    text = page.read_text(encoding="utf-8")
    found = {m["name"] for m in GENERATED_PART.finditer(text)}
    if missing := sorted(set(parts) - found):
        sys.exit(f"{shown(page)}: no generated part named {', '.join(missing)}")

    def replace(m: re.Match[str]) -> str:
        whole, start = m.group(0), m.start()
        body = f"\n{parts[m['name']]}\n" if m["name"] in parts else m["body"]
        return whole[: m.start("body") - start] + body + whole[m.end("body") - start :]

    return GENERATED_PART.sub(replace, text)


def outputs(heki: Path, rules: list[dict], registry: dict, precision: dict) -> dict[Path, str]:
    files = {
        RULES_DIR / "index.md": rules_index(rules, registry["policy"]),
        CLI_PAGE: cli_page(heki),
        EXPERIMENTAL_PAGE: experimental_page(registry, rules),
        PRECISION_PAGE: with_generated_parts(
            PRECISION_PAGE,
            {
                "certifications": certifications_table(precision, rules),
                "harm": harm_table(precision),
                "measurements": measurements_table(precision, rules),
            },
        ),
        RECOMMEND_PAGE: with_generated_parts(RECOMMEND_PAGE, {"report": recommend_example(heki)}),
        GETTING_STARTED_PAGE: with_generated_parts(
            GETTING_STARTED_PAGE, {"default-rules": default_rules_list(rules)}
        ),
        RECOMMEND_SCHEMA: run(heki, "recommend", "--output-format-json-schema"),
        EXAMPLE_IMAGE: example_image(heki),
    }
    for r in rules:
        files[RULES_DIR / f"{r['slug']}.md"] = rule_page(r, registry["policy"])
    return files


def uncertified_exact_rules(rules: list[dict]) -> list[str]:
    """The exact rules without a certification whose census and holdout run found no false
    claim."""
    stale = []
    for r in rules:
        certification = r.get("certification")
        if r["certainty"] != "exact":
            continue
        if certification is None:
            stale.append(f"{r['code']}: no certification")
        else:
            census, holdout = certification["census"], certification["holdout"]
            if census["false_claims"] > 0 or holdout["false_claims"] > 0:
                stale.append(
                    f"{r['code']}: {census['false_claims']} false claim(s) in the census and "
                    f"{holdout['false_claims']} in the holdout run (exact needs none)"
                )
    return stale


def page_premises(doc: str) -> list[str]:
    """The premise names a rule page lists under "Its premises:" in its claim section."""
    lines = doc.splitlines()
    try:
        start = next(i for i, line in enumerate(lines) if line.strip() == CLAIM_SECTION)
    except StopIteration:
        return []
    names = []
    listing = False
    for line in lines[start + 1 :]:
        if line.startswith("## "):
            break
        if line.strip() == "Its premises:":
            listing = True
            continue
        match = re.match(r"- \*\*([^*]+)\*\*", line) if listing else None
        if match:
            names.append(match.group(1))
    return names


def premises_disagreeing(rules: list[dict]) -> list[str]:
    """The exact rules whose page lists other premises than the premise table
    (`crates/heki_rules/src/premises.rs`), in another order, or under other names."""
    out = []
    for r in rules:
        table = [p["name"] for p in r.get("premises", [])]
        page = page_premises(r["doc"])
        if (table or r["certainty"] == "exact") and table != page:
            out.append(f"{r['code']}: the page lists {page}, the premise table {table}")
    return out


def rules_without_claims(rules: list[dict]) -> list[str]:
    """The rules whose documentation does not say what a report states."""
    return [
        f"{r['code']}: no `{CLAIM_SECTION}` section"
        for r in rules
        if not any(line.strip() == CLAIM_SECTION for line in r["doc"].splitlines())
    ]


def stale_opt_in_lists(rules: list[dict]) -> list[str]:
    """The guides' opt-in rule lists that do not name exactly the opt-in rules."""
    opt_in = {r["code"] for r in rules if r["activation"] == "opt-in"}
    stale = []
    for page in sorted(DOCS.glob("*.md")):
        text = page.read_text(encoding="utf-8")
        for m in OPT_IN_LIST.finditer(text):
            listed = set(RULE_CODE.findall(m.group(1)))
            if listed != opt_in:
                line = text.count("\n", 0, m.start()) + 1
                missing = ", ".join(sorted(opt_in - listed)) or "-"
                extra = ", ".join(sorted(listed - opt_in)) or "-"
                stale.append(f"{shown(page)}:{line}: missing {missing}; not opt-in {extra}")
    return stale


def hand_written_pages() -> list[Path]:
    """The README, `ARCHITECTURE.md`, and the site's pages; not the internal design docs, whose
    tables record measurements and decisions of their time."""
    site = tomllib.loads((ROOT / "zensical.toml").read_text(encoding="utf-8"))["project"]
    internal = {DOCS / name for name in site["exclude_docs"].split()}
    pages = [ROOT / "README.md", ROOT / "ARCHITECTURE.md", *sorted(DOCS.glob("*.md"))]
    return [
        p
        for p in pages
        if p not in internal and not p.read_text(encoding="utf-8").startswith(GENERATED)
    ]


def rule_cell_codes(row: str, codes: set[str]) -> set[str]:
    """The rules a table row names in cells of their own (`` `EFF103`, `EFF102` ``, a link)."""
    named = set()
    for cell in TABLE_CELL_SEPARATOR.split(row.strip().strip("|")):
        tokens = [
            t.strip() for t in LINK.sub(r"\1", cell).replace("`", "").replace("*", "").split(",")
        ]
        if all(t in codes for t in tokens):
            named.update(tokens)
    return named


def list_items(text: str):
    """The items of the Markdown lists in `text`, each with its continuation lines."""
    item: list[str] = []
    for line in text.splitlines():
        if LIST_ITEM.match(line) or not line.strip():
            if item:
                yield " ".join(item)
            item = [line.strip()] if line.strip() else []
        elif item:
            item.append(line.strip())
    if item:
        yield " ".join(item)


def stale_row_marks(rules: list[dict], word: str, marked_codes: set[str]) -> list[str]:
    """The hand-written pages' table rows that name rules in cells of their own and say `word`
    other than exactly when one of them is in `marked_codes`."""
    codes = {r["code"] for r in rules}
    stale = []
    for page in hand_written_pages():
        for number, row in enumerate(page.read_text(encoding="utf-8").splitlines(), 1):
            named = rule_cell_codes(row, codes) if row.lstrip().startswith("|") else set()
            marked = word in row.lower()
            if named and marked != bool(named & marked_codes):
                listed = ", ".join(sorted(named))
                wrong = f"says {word}" if marked else f"does not say {word}"
                stale.append(f"{shown(page)}:{number}: the row of {listed} {wrong}")
    return stale


def stale_experimental_marks(rules: list[dict], registry: dict) -> list[str]:
    """The hand-written pages' marks of experimental features that disagree with the registry."""
    experimental = {r["code"] for r in rules if r["experimental"]}
    stale = stale_row_marks(rules, "experimental", experimental)
    text = CHANGELOG.read_text(encoding="utf-8")
    starts = list(CHANGELOG_SECTION.finditer(text)) + [None]
    sections = {
        m.group(1): text[m.end() : n.start() if n else len(text)]
        for m, n in zip(starts, starts[1:])
    }
    for feature in sorted(registry["features"], key=lambda f: f["id"]):
        target = re.compile(rf"(?<![\w-]){re.escape(feature['target'])}(?![\w-])")
        section = sections.get(feature["since"])
        if section is not None and not any(
            target.search(item) and "experimental" in item.lower() for item in list_items(section)
        ):
            stale.append(
                f"{shown(CHANGELOG)}: [{feature['since']}] does not call "
                f"{feature['target']} experimental"
            )
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    # Resolved: `subprocess` looks a bare `heki` (what `Path("./heki")` prints) up on `PATH`.
    parser.add_argument(
        "--heki",
        type=lambda p: Path(p).resolve(),
        default=ROOT / "target" / "release" / "heki",
    )
    parser.add_argument("--check", action="store_true", help="fail if a generated page is stale")
    args = parser.parse_args()
    rules = json.loads(run(args.heki, "rule", "--all", "--output-format", "json"))
    registry = json.loads(run(args.heki, "dump-experimental"))
    precision = json.loads(run(args.heki, "dump-precision"))
    heuristic = {r["code"] for r in rules if r["certainty"] == "heuristic"}
    disagreements = {
        "Opt-in rule lists in the guides disagree with the rules": stale_opt_in_lists(rules),
        "Experimental features are marked differently from the registry": (
            stale_experimental_marks(rules, registry)
        ),
        "Heuristic rules are marked differently from the rules": (
            stale_row_marks(rules, "heuristic", heuristic)
        ),
        "Exact rules lack their certification in crates/heki_rules/src/precision.rs": (
            uncertified_exact_rules(rules)
        ),
        "Rules do not say what a report states": rules_without_claims(rules),
        "Rule pages and the premise table list different premises": premises_disagreeing(rules),
    }
    if any(disagreements.values()):
        for heading, entries in disagreements.items():
            if entries:
                print(f"{heading} (edit them by hand):")
                for entry in entries:
                    print(f"  {entry}")
        return 1
    files = outputs(args.heki, rules, registry, precision)
    stale = sorted(
        shown(p)
        for p, text in files.items()
        if not p.exists() or p.read_text(encoding="utf-8") != text
    )
    expected = {p.name for p in files if p.parent == RULES_DIR}
    extra = sorted(
        shown(p)
        for p in RULES_DIR.glob("*.md")
        if p.name not in expected
    ) if RULES_DIR.exists() else []
    if args.check:
        if stale or extra:
            print("Generated docs are out of date; run `python scripts/build_docs.py`:")
            for p in stale + extra:
                print(f"  {p}")
            return 1
        print(f"Generated docs are up to date ({len(files)} files).")
        return 0
    for p in extra:
        (ROOT / p).unlink()
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        # LF on every platform, as the checkout keeps them (`.gitattributes`): Python would
        # write CRLF on Windows.
        p.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {len(files)} files ({len(stale)} changed, {len(extra)} removed).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
