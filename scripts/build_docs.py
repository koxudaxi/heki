"""Generate the rules reference and the CLI reference from the `heki` binary.

- `docs/rules/index.md`: every rule, grouped by family, in Ruff's rules-page layout.
- `docs/rules/<slug>.md`: one page per rule (metadata + the rule documentation that
  `heki rule <CODE>` prints, kept in `crates/heki_rules/rule-docs/<CODE>.md`).
- `docs/cli-reference.md`: the `--help` output of every command.
- `docs/experimental.md`: the experimental features (`crates/heki_rules/src/experimental.rs`).

The hand-written pages are checked against the rules: the guides' lists of opt-in rules, and
the experimental features (in the README, `ARCHITECTURE.md`, and the site's pages, a table row
that names a rule in a cell of its own says "experimental" exactly when the rule is; the
`CHANGELOG.md` section of the release an entry names as `since` calls its target
experimental).

Usage:
    python scripts/build_docs.py --heki target/release/heki
    python scripts/build_docs.py --heki target/release/heki --check  # CI: fail when stale
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
RULES_DIR = DOCS / "rules"
CLI_PAGE = DOCS / "cli-reference.md"
EXPERIMENTAL_PAGE = DOCS / "experimental.md"
CHANGELOG = ROOT / "CHANGELOG.md"

FAMILIES = {
    "Mut": (
        "Mutation & State (MUT)",
        "Shared state written behind its owner's back: stale caches, write-ownership "
        "contracts, shared return values, and effect regressions against a saved snapshot.",
    ),
    "Eff": (
        "Execution Effects (EFF)",
        "Work that runs where it should not: blocking calls on the event loop, clients and "
        "queries inside loops.",
    ),
    "Data": (
        "Data Pipelines (DATA)",
        "Quadratic re-allocation of DataFrames and arrays across loop iterations.",
    ),
    "Opt": (
        "Complexity Rewrites (OPT)",
        "Quadratic patterns heki can rewrite, each proven safe by the alias analysis before a "
        "fix is offered.",
    ),
}

GENERATED = "<!-- Generated by scripts/build_docs.py. Do not edit by hand. -->\n"

# A hand-written list of the opt-in rules in the guides: "Opt-in rules (`EFF105`, ...)".
OPT_IN_LIST = re.compile(r"[Oo]pt-in rules\s+\(([^)]*)\)")
RULE_CODE = re.compile(r"\b[A-Z]+\d+\b")
TABLE_CELL_SEPARATOR = re.compile(r"(?<!\\)\|")
LINK = re.compile(r"\[([^\]]+)]\([^)]+\)")
CHANGELOG_SECTION = re.compile(r"^## \[([^\]]+)]", re.MULTILINE)
LIST_ITEM = re.compile(r"^\s*[-*] ")

CLI_COMMANDS = [
    ([], "heki"),
    (["check"], "heki check"),
    (["server"], "heki server"),
    (["rule"], "heki rule"),
    (["snapshot"], "heki snapshot"),
    (["assumptions"], "heki assumptions"),
    (["inspect"], "heki inspect"),
]


def run(heki: Path, *args: str) -> str:
    out = subprocess.run([str(heki), *args], capture_output=True, text=True, check=False)
    if out.returncode != 0:
        sys.exit(f"`heki {' '.join(args)}` failed ({out.returncode}):\n{out.stderr}")
    return out.stdout


def fix_label(rule: dict) -> str:
    if rule["auto_fix_default"]:
        return "Safe fix (`--fix`)"
    if rule["size_dependent_fix"]:
        return "Proven-safe suggestion (`--fix --include-size-dependent`)"
    return "No automatic fix"


def badges(rule: dict) -> str:
    marks = []
    if rule["auto_fix_default"]:
        marks.append("🛠️")
    elif rule["size_dependent_fix"]:
        marks.append("🔧")
    if not rule["default_enabled"]:
        marks.append("🔌")
    if rule["experimental"]:
        marks.append("🧪")
    return " ".join(marks)


def rules_index(rules: list[dict], policy: str) -> str:
    lines = [
        GENERATED,
        "# Rules",
        "",
        f"heki has {len(rules)} rules in four families. Every rule is enabled by default except "
        "the opt-in rules marked 🔌, which need their exact code or name in `select` / "
        "`extend-select` (a prefix such as `EFF` does not enable them).",
        "",
        "## Legend",
        "",
        "- 🛠️ The fix is applied by `heki check --fix` when heki proves it safe.",
        "- 🔧 A proven-safe rewrite applied only with `--fix --include-size-dependent` or in "
        "functions a `--profile` dump shows hot (it can be slower for tiny inputs).",
        "- 🔌 Opt-in rule.",
        f"- 🧪 Experimental rule. {policy} See [Experimental Features](../experimental.md).",
        "",
    ]
    for family, (title, blurb) in FAMILIES.items():
        members = [r for r in rules if r["family"] == family]
        if not members:
            continue
        lines += [f"## {title}", "", blurb, "", "| Code | Name | Message | |", "| ---- | ---- | ------- | ------: |"]
        for r in members:
            summary = r["summary"].replace("|", "\\|")
            lines.append(f"| {r['code']} | [{r['slug']}]({r['slug']}.md) | {summary} | {badges(r)} |")
        lines.append("")
    return "\n".join(lines)


def rule_page(rule: dict, policy: str) -> str:
    title, _ = FAMILIES[rule["family"]]
    state = ["Enabled by default" if rule["default_enabled"] else "Opt-in"]
    note = []
    if rule["experimental"]:
        state.append("Experimental")
        note = [
            '!!! warning "Experimental"',
            "",
            f"    {rule['experimental']['reason']} {policy} See "
            "[Experimental Features](../experimental.md).",
            "",
        ]
    return "\n".join(
        [
            GENERATED,
            f"# {rule['slug']} ({rule['code']})",
            "",
            f"Family: {title} · {' · '.join(state)} · Severity `{rule['default_severity']}` · {fix_label(rule)}",
            "",
            rule["summary"],
            "",
            *note,
            rule["doc"].rstrip(),
            "",
        ]
    )


def experimental_target(feature: dict, slugs: dict[str, str]) -> str:
    """The target as a code span, linked to the rule's page for a rule."""
    if feature["kind"] == "rule":
        return f"[`{feature['target']}`](rules/{slugs[feature['target']]}.md)"
    return f"`{feature['target']}`"


def experimental_page(registry: dict, rules: list[dict]) -> str:
    slugs = {r["code"]: r["slug"] for r in rules}
    features = sorted(registry["features"], key=lambda f: f["id"])
    lines = [
        GENERATED,
        "# Experimental Features",
        "",
        f"{registry['policy']} A feature leaves this page when it becomes stable.",
        "",
        "An experimental rule is never enabled by default: it runs only when `select` or "
        "`extend-select` names its code or name, and `heki check` then reports it like any "
        "other rule. `heki rule <CODE>` and the rule's page say that it is experimental.",
        "",
        "| ID | Kind | Target | Since | Tracking |",
        "| -- | ---- | ------ | ----- | -------- |",
    ]
    for f in features:
        tracking = f"<{f['tracking']}>" if f["tracking"] else "-"
        lines.append(
            f"| `{f['id']}` | {f['kind']} | {experimental_target(f, slugs)} | {f['since']} "
            f"| {tracking} |"
        )
    for f in features:
        lines += [
            "",
            f"## `{f['id']}`",
            "",
            f"- **Kind:** {f['kind']}",
            f"- **Target:** {experimental_target(f, slugs)}",
            f"- **Since:** {f['since']}",
        ]
        if f["tracking"]:
            lines.append(f"- **Tracking:** <{f['tracking']}>")
        lines += ["", f["reason"]]
    return "\n".join(lines) + "\n"


def cli_page(heki: Path) -> str:
    lines = [
        GENERATED,
        "# CLI Reference",
        "",
        "Exit codes: `0` no diagnostics, `1` diagnostics (or Ratchet regressions, or pending "
        "`--diff` changes), `2` configuration / I/O / syntax errors.",
        "",
    ]
    for args, title in CLI_COMMANDS:
        help_text = run(heki, *args, "--help").rstrip()
        lines += [f"## `{title}`", "", "```text", help_text, "```", ""]
    return "\n".join(lines)


def outputs(heki: Path, rules: list[dict], registry: dict) -> dict[Path, str]:
    files = {
        RULES_DIR / "index.md": rules_index(rules, registry["policy"]),
        CLI_PAGE: cli_page(heki),
        EXPERIMENTAL_PAGE: experimental_page(registry, rules),
    }
    for r in rules:
        files[RULES_DIR / f"{r['slug']}.md"] = rule_page(r, registry["policy"])
    return files


def stale_opt_in_lists(rules: list[dict]) -> list[str]:
    """The guides' opt-in rule lists that do not name exactly the opt-in rules."""
    opt_in = {r["code"] for r in rules if not r["default_enabled"]}
    stale = []
    for page in sorted(DOCS.glob("*.md")):
        text = page.read_text(encoding="utf-8")
        for m in OPT_IN_LIST.finditer(text):
            listed = set(RULE_CODE.findall(m.group(1)))
            if listed != opt_in:
                line = text.count("\n", 0, m.start()) + 1
                missing = ", ".join(sorted(opt_in - listed)) or "-"
                extra = ", ".join(sorted(listed - opt_in)) or "-"
                stale.append(f"{page.relative_to(ROOT)}:{line}: missing {missing}; not opt-in {extra}")
    return stale


def hand_written_pages() -> list[Path]:
    """The README, `ARCHITECTURE.md`, and the site's pages; not the internal design docs, whose
    tables record measurements and decisions of their time."""
    site = tomllib.loads((ROOT / "zensical.toml").read_text(encoding="utf-8"))["project"]
    internal = {DOCS / name for name in site["exclude_docs"].split()}
    pages = [ROOT / "README.md", ROOT / "ARCHITECTURE.md", *sorted(DOCS.glob("*.md"))]
    return [
        p
        for p in pages
        if p not in internal and not p.read_text(encoding="utf-8").startswith(GENERATED)
    ]


def rule_cell_codes(row: str, codes: set[str]) -> set[str]:
    """The rules a table row names in cells of their own (`` `EFF103`, `EFF102` ``, a link)."""
    named = set()
    for cell in TABLE_CELL_SEPARATOR.split(row.strip().strip("|")):
        tokens = [
            t.strip() for t in LINK.sub(r"\1", cell).replace("`", "").replace("*", "").split(",")
        ]
        if all(t in codes for t in tokens):
            named.update(tokens)
    return named


def list_items(text: str):
    """The items of the Markdown lists in `text`, each with its continuation lines."""
    item: list[str] = []
    for line in text.splitlines():
        if LIST_ITEM.match(line) or not line.strip():
            if item:
                yield " ".join(item)
            item = [line.strip()] if line.strip() else []
        elif item:
            item.append(line.strip())
    if item:
        yield " ".join(item)


def stale_experimental_marks(rules: list[dict], registry: dict) -> list[str]:
    """The hand-written pages' marks of experimental features that disagree with the registry."""
    codes = {r["code"] for r in rules}
    experimental = {r["code"]: r["experimental"] for r in rules if r["experimental"]}
    stale = []
    for page in hand_written_pages():
        for number, row in enumerate(page.read_text(encoding="utf-8").splitlines(), 1):
            named = rule_cell_codes(row, codes) if row.lstrip().startswith("|") else set()
            marked = "experimental" in row.lower()
            if named and marked != bool(named & experimental.keys()):
                listed = ", ".join(sorted(named))
                wrong = "says experimental" if marked else "does not say experimental"
                stale.append(f"{page.relative_to(ROOT)}:{number}: the row of {listed} {wrong}")
    text = CHANGELOG.read_text(encoding="utf-8")
    starts = list(CHANGELOG_SECTION.finditer(text)) + [None]
    sections = {
        m.group(1): text[m.end() : n.start() if n else len(text)]
        for m, n in zip(starts, starts[1:])
    }
    for feature in sorted(registry["features"], key=lambda f: f["id"]):
        target = re.compile(rf"(?<![\w-]){re.escape(feature['target'])}(?![\w-])")
        section = sections.get(feature["since"])
        if section is not None and not any(
            target.search(item) and "experimental" in item.lower() for item in list_items(section)
        ):
            stale.append(
                f"{CHANGELOG.relative_to(ROOT)}: [{feature['since']}] does not call "
                f"{feature['target']} experimental"
            )
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    # Resolved: `subprocess` looks a bare `heki` (what `Path("./heki")` prints) up on `PATH`.
    parser.add_argument(
        "--heki",
        type=lambda p: Path(p).resolve(),
        default=ROOT / "target" / "release" / "heki",
    )
    parser.add_argument("--check", action="store_true", help="fail if a generated page is stale")
    args = parser.parse_args()
    rules = json.loads(run(args.heki, "rule", "--all", "--output-format", "json"))
    registry = json.loads(run(args.heki, "dump-experimental"))
    disagreements = {
        "Opt-in rule lists in the guides disagree with the rules": stale_opt_in_lists(rules),
        "Experimental features are marked differently from the registry": (
            stale_experimental_marks(rules, registry)
        ),
    }
    if any(disagreements.values()):
        for heading, entries in disagreements.items():
            if entries:
                print(f"{heading} (edit them by hand):")
                for entry in entries:
                    print(f"  {entry}")
        return 1
    files = outputs(args.heki, rules, registry)
    stale = sorted(
        str(p.relative_to(ROOT))
        for p, text in files.items()
        if not p.exists() or p.read_text(encoding="utf-8") != text
    )
    expected = {p.name for p in files if p.parent == RULES_DIR}
    extra = sorted(
        str(p.relative_to(ROOT))
        for p in RULES_DIR.glob("*.md")
        if p.name not in expected
    ) if RULES_DIR.exists() else []
    if args.check:
        if stale or extra:
            print("Generated docs are out of date; run `python scripts/build_docs.py`:")
            for p in stale + extra:
                print(f"  {p}")
            return 1
        print(f"Generated docs are up to date ({len(files)} files).")
        return 0
    RULES_DIR.mkdir(parents=True, exist_ok=True)
    for p in extra:
        (ROOT / p).unlink()
    for p, text in files.items():
        # LF on every platform, as the checkout keeps them (`.gitattributes`): Python would
        # write CRLF on Windows.
        p.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {len(files)} files ({len(stale)} changed, {len(extra)} removed).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
